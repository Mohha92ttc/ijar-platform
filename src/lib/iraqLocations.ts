export function formatEquipmentLocation(governorate: string, area?: string | null): string {
  const g = (governorate || '').trim();
  const a = (area || '').trim();
  if (!g) return a || '';
  if (!a) return g;
  return `${g} - ${a}`;
}

export function parseLocationHint(location: string): { governorate: string; area: string } {
  const raw = String(location || '').trim();
  if (!raw) return { governorate: '', area: '' };
  const parts = raw.split(/\s*[-–—]\s*/);
  if (parts.length >= 2) {
    return { governorate: parts[0].trim(), area: parts.slice(1).join(' - ').trim() };
  }
  const known = IRAQ_GOVERNORATES.find((g) => raw === g || raw.startsWith(g));
  if (known) return { governorate: known, area: raw === known ? '' : raw.replace(known, '').replace(/^[\s\-–—]+/, '') };
  return { governorate: raw, area: '' };
}
